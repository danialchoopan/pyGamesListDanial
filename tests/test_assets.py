"""Tests for the asset manager and audio service.

The two guarantees the hub depends on are tested here:

  1. Loading an asset never raises - a missing file returns ``None``.
  2. Audio calls never raise - they are safe no-ops when the mixer is absent
     (e.g. in CI) or a sound/music name is unknown.

The audio tests are deliberately lenient: whether the mixer actually opens
depends on the host, so they assert "did not raise" rather than "made noise".
"""

from __future__ import annotations

import io
import wave
from pathlib import Path

import pygame

from assets import (
    IMAGE_EXTENSIONS,
    MUSIC_EXTENSIONS,
    SFX_RECIPES,
    SOUND_EXTENSIONS,
    AssetManager,
    AudioService,
    ToneRecipe,
    mixer_ready,
    note_freq,
    render_pcm,
    wav_bytes,
)
from utils import Settings


def test_sfx_recipes_have_sane_parameters() -> None:
    assert SFX_RECIPES, "at least one recipe should be defined"
    for name, recipe in SFX_RECIPES.items():
        assert isinstance(recipe, ToneRecipe), name
        assert recipe.freq > 0, name
        assert recipe.duration > 0, name
        assert 0.0 <= recipe.volume <= 1.0, name
        assert recipe.wave in {"sine", "square", "triangle", "noise"}, name


def test_every_named_sfx_used_by_games_exists() -> None:
    # The three enhanced games call audio.play(...) with these names; if a
    # recipe is ever renamed this test catches the dangling reference.
    required = {
        # platformer
        "jump", "coin", "stomp", "powerup", "checkpoint", "hurt", "level_clear",
        # space shooter
        "shoot", "enemy_shoot", "explode", "hit", "boss_hit", "player_hit",
        "wave_clear", "buy", "achievement",
        # breakout
        "paddle", "brick", "brick_hard", "laser", "life_lost",
    }
    assert required <= set(SFX_RECIPES)


def test_note_freq_uses_a440_pitch_standard() -> None:
    assert note_freq(69) == 440.0  # MIDI 69 is A4
    assert note_freq(81) == 880.0  # one octave up doubles the frequency
    assert note_freq(57) == 220.0  # one octave down halves it


def test_render_pcm_length_matches_duration() -> None:
    recipe = ToneRecipe(freq=440.0, duration=0.05)
    rate = 8000
    samples = render_pcm(recipe, sample_rate=rate)
    assert len(samples) == int(0.05 * rate)


def test_wav_bytes_round_trips_through_wave_module() -> None:
    recipe = ToneRecipe(freq=440.0, duration=0.02)
    samples = render_pcm(recipe, sample_rate=8000)
    data = wav_bytes(samples, 8000)
    assert data[:4] == b"RIFF" and data[8:12] == b"WAVE"
    # Re-open the header to prove it is a valid, decodable WAV.
    with wave.open(io.BytesIO(data)) as wav_file:
        assert wav_file.getframerate() == 8000
        assert wav_file.getnchannels() == 1
        assert len(wav_file.readframes(wav_file.getnframes())) > 0


def test_extension_tables_are_ordered_and_complete() -> None:
    assert SOUND_EXTENSIONS[0] == ".wav"
    assert MUSIC_EXTENSIONS[0] == ".ogg"
    assert ".png" in IMAGE_EXTENSIONS


def test_missing_assets_return_none_without_raising(tmp_path: Path) -> None:
    mgr = AssetManager(root=tmp_path)
    assert mgr.sound("nope") is None
    assert mgr.image("nope") is None
    assert mgr.music_path("nope") is None
    assert mgr.music_source("nope") is not None  # falls back to a generated loop
    assert mgr.loaded_files == 0


def test_image_cache_reuses_same_surface(tmp_path: Path) -> None:
    img_dir = tmp_path / "images"
    img_dir.mkdir()
    pygame.image.save(pygame.Surface((4, 4)), str(img_dir / "hero.png"))

    mgr = AssetManager(root=tmp_path)
    first = mgr.image("hero")
    second = mgr.image("hero")
    assert first is not None and first is second  # cached, not reloaded
    assert first.get_size() == (4, 4)
    assert mgr.loaded_files == 1


def test_image_loader_tolerates_corrupt_file(tmp_path: Path) -> None:
    img_dir = tmp_path / "images"
    img_dir.mkdir()
    (img_dir / "broken.png").write_bytes(b"not a real png")
    assert AssetManager(root=tmp_path).image("broken") is None


def test_music_source_prefers_real_file_over_generated(tmp_path: Path) -> None:
    music_dir = tmp_path / "music"
    music_dir.mkdir()
    (music_dir / "title.ogg").write_bytes(b"fake ogg payload")

    mgr = AssetManager(root=tmp_path)
    assert mgr.music_path("title") == music_dir / "title.ogg"
    # A real file resolves to its path; unknown tracks get generated bytes.
    assert isinstance(mgr.music_source("title"), str)


def test_audio_service_play_and_music_are_safe_no_ops(tmp_path: Path) -> None:
    svc = AudioService(AssetManager(root=tmp_path))
    svc.play("does-not-exist")          # unknown name -> no-op
    svc.play_music(tmp_path / "x.ogg")  # Path accepted; missing -> no-op-safe
    svc.play_music("overworld")         # bare name -> generated loop fallback
    assert svc.current_track in ("overworld", None)
    svc.pause_music()
    svc.resume_music()
    svc.stop_music()
    assert svc.current_track is None


def test_audio_service_zero_volume_is_effective_mute(tmp_path: Path) -> None:
    svc = AudioService(AssetManager(root=tmp_path))
    # Muting is done through volumes, not a flag; zero volume must not raise.
    svc.update_settings(Settings(sfx_volume=0.0, music_volume=0.0))
    assert svc.settings.sfx_volume == 0.0
    svc.play("jump")
    svc.play_music("overworld")
    svc.stop_music()


def test_audio_service_update_settings_clamps_volume(tmp_path: Path) -> None:
    svc = AudioService(AssetManager(root=tmp_path))
    svc.update_settings(Settings(sfx_volume=5.0, music_volume=-1.0))  # clamps
    assert 0.0 <= svc.settings.sfx_volume <= 1.0
    assert 0.0 <= svc.settings.music_volume <= 1.0


def test_mixer_ready_returns_bool() -> None:
    assert isinstance(mixer_ready(), bool)
